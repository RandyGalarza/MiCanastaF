-- 1. Tabla de Categorias
CREATE TABLE IF NOT EXISTS public.categorias (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion TEXT NOT NULL
);

-- 2. Tabla de Comercios
CREATE TABLE IF NOT EXISTS public.comercios (
    id_comercio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    direccion TEXT,
    telefono TEXT,
    tipo_comercio TEXT,
    com_estado INT NOT NULL DEFAULT 1
);

-- 3. Tabla de Usuarios
CREATE TABLE IF NOT EXISTS public.usuarios (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    apellido TEXT NOT NULL,
    telefono TEXT,
    correo TEXT NOT NULL UNIQUE,
    rol TEXT NOT NULL DEFAULT 'usuario',
    id_comercio BIGINT REFERENCES public.comercios(id_comercio) ON UPDATE CASCADE ON DELETE SET NULL,
    fecha_creacion DATE NOT NULL DEFAULT CURRENT_DATE,
    usu_estado INT NOT NULL DEFAULT 1
);

-- Auth credentials belong to Supabase Auth, never the synchronized profile table.
ALTER TABLE public.usuarios DROP COLUMN IF EXISTS contrasena;

-- 4. Tabla de Presupuestos
CREATE TABLE IF NOT EXISTS public.presupuestos (
    id_presupuesto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES public.usuarios(id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
    nombre TEXT NOT NULL,
    monto NUMERIC NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    pre_estado INT NOT NULL DEFAULT 1
);

-- 5. Tabla de Productos
CREATE TABLE IF NOT EXISTS public.productos (
    id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria BIGINT NOT NULL REFERENCES public.categorias(id_categoria) ON UPDATE CASCADE ON DELETE RESTRICT,
    id_comercio BIGINT REFERENCES public.comercios(id_comercio) ON UPDATE CASCADE ON DELETE RESTRICT,
    nombre TEXT NOT NULL,
    descripcion TEXT,
    unidad_medida TEXT NOT NULL,
    marca TEXT,
    imagen_url TEXT,
    pro_estado INT NOT NULL DEFAULT 1
);

-- Una calificación por usuario y producto; el promedio se calcula en la app.
CREATE TABLE IF NOT EXISTS public.calificaciones_productos (
    id_calificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto BIGINT NOT NULL REFERENCES public.productos(id_producto) ON UPDATE CASCADE ON DELETE CASCADE,
    id_usuario BIGINT NOT NULL REFERENCES public.usuarios(id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
    puntuacion INT NOT NULL CHECK (puntuacion BETWEEN 1 AND 5),
    fecha_calificacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (id_producto, id_usuario)
);

-- 6. Tabla de Precios
CREATE TABLE IF NOT EXISTS public.precios (
    id_precio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto BIGINT NOT NULL REFERENCES public.productos(id_producto) ON UPDATE CASCADE ON DELETE CASCADE,
    id_comercio BIGINT NOT NULL REFERENCES public.comercios(id_comercio) ON UPDATE CASCADE ON DELETE CASCADE,
    precio NUMERIC NOT NULL,
    disponible INT NOT NULL DEFAULT 1,
    fecha_registro DATE NOT NULL DEFAULT CURRENT_DATE
);

-- 7. Tabla de Listas de Compra
CREATE TABLE IF NOT EXISTS public.listas_compra (
    id_lista BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES public.usuarios(id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
    nombre TEXT NOT NULL,
    fecha_creacion DATE NOT NULL DEFAULT CURRENT_DATE,
    lis_estado INT NOT NULL DEFAULT 1
);

-- 8. Detalles de Lista de Compra
CREATE TABLE IF NOT EXISTS public.detalles_lista_compra (
    id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_lista BIGINT NOT NULL REFERENCES public.listas_compra(id_lista) ON UPDATE CASCADE ON DELETE CASCADE,
    id_producto BIGINT NOT NULL REFERENCES public.productos(id_producto) ON UPDATE CASCADE ON DELETE RESTRICT,
    cantidad NUMERIC NOT NULL DEFAULT 1,
    comprado INT NOT NULL DEFAULT 0
);

-- Compras cerradas e items congelados para consultar el historial aun si
-- cambian los precios o el catálogo.
CREATE TABLE IF NOT EXISTS public.compras (
    id_compra BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES public.usuarios(id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
    id_lista BIGINT,
    nombre_lista TEXT NOT NULL,
    numero_factura TEXT NOT NULL UNIQUE,
    fecha_compra TIMESTAMPTZ NOT NULL,
    subtotal NUMERIC NOT NULL,
    descuento NUMERIC NOT NULL DEFAULT 0,
    total NUMERIC NOT NULL,
    detalles_json TEXT NOT NULL
);

-- 9. Detalles de Presupuesto
CREATE TABLE IF NOT EXISTS public.detalles_presupuesto (
    id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_presupuesto BIGINT NOT NULL REFERENCES public.presupuestos(id_presupuesto) ON UPDATE CASCADE ON DELETE CASCADE,
    id_producto BIGINT NOT NULL REFERENCES public.productos(id_producto) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- 10. Facturas
CREATE TABLE IF NOT EXISTS public.facturas (
    id_factura BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES public.usuarios(id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
    id_comercio BIGINT NOT NULL REFERENCES public.comercios(id_comercio) ON UPDATE CASCADE ON DELETE RESTRICT,
    id_presupuesto BIGINT NOT NULL REFERENCES public.presupuestos(id_presupuesto) ON UPDATE CASCADE ON DELETE RESTRICT,
    numero_factura TEXT NOT NULL,
    fecha_factura DATE NOT NULL,
    subtotal NUMERIC NOT NULL,
    impuesto NUMERIC NOT NULL DEFAULT 0,
    descuento NUMERIC NOT NULL DEFAULT 0,
    total NUMERIC NOT NULL,
    fecha_creacion DATE NOT NULL DEFAULT CURRENT_DATE,
    fac_estado INT NOT NULL DEFAULT 1
);

-- 11. Detalles Factura
CREATE TABLE IF NOT EXISTS public.detalles_factura (
    id_detalle_factura BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_factura BIGINT NOT NULL REFERENCES public.facturas(id_factura) ON UPDATE CASCADE ON DELETE CASCADE,
    id_usuario BIGINT NOT NULL REFERENCES public.usuarios(id_usuario) ON UPDATE CASCADE ON DELETE CASCADE,
    cantidad NUMERIC NOT NULL,
    precio_unitario NUMERIC NOT NULL,
    descuento NUMERIC NOT NULL DEFAULT 0,
    subtotal NUMERIC NOT NULL
);

-- ==========================================================
-- POLÍTICAS RLS (Row Level Security) O PERMISOS PARA LA API
-- Permitir lectura y escritura con la clave anónima de la app:
-- ==========================================================
ALTER TABLE public.categorias ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.comercios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.presupuestos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.productos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.calificaciones_productos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.precios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.listas_compra ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.detalles_lista_compra ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.compras ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.detalles_presupuesto ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.facturas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.detalles_factura ENABLE ROW LEVEL SECURITY;

-- Políticas permisivas para sincronización con la app móvil (anon)
DO $$
DECLARE
    tbl text;
BEGIN
    FOR tbl IN
        SELECT table_name
        FROM information_schema.tables
        WHERE table_schema = 'public'
          AND table_type = 'BASE TABLE'
    LOOP
        EXECUTE format('DROP POLICY IF EXISTS "Anon acceso total %I" ON public.%I;', tbl, tbl);
        EXECUTE format('CREATE POLICY "Anon acceso total %I" ON public.%I FOR ALL USING (true) WITH CHECK (true);', tbl, tbl);
    END LOOP;
END $$;
