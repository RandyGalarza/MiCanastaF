-- Políticas permisivas para sincronización con la app móvil (anon)
DO $$
DECLARE
    tbl text;
BEGIN
    FOR tbl IN
        SELECT table_name
        FROM information_schema.tables
        WHERE table_schema = 'public'
          AND table_type = 'BASE TABLE'
          AND table_name NOT IN (
              'hogares',
              'hogar_miembros',
              'invitaciones_hogar',
              'movimientos_hogar_compartidos',
              'chat_cuotas_diarias'
          )
    LOOP
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I;', 'Anon acceso total ' || tbl, tbl);
        EXECUTE format('CREATE POLICY %I ON public.%I FOR ALL USING (true) WITH CHECK (true);', 'Anon acceso total ' || tbl, tbl);
    END LOOP;
END $$;

-- Funciones auxiliares con privilegios limitados para evitar recursión en políticas RLS.
CREATE OR REPLACE FUNCTION public.es_miembro_hogar(p_id_hogar UUID)
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.hogar_miembros
        WHERE id_hogar = p_id_hogar
          AND auth_user_id = (SELECT auth.uid())
    );
$$;

CREATE OR REPLACE FUNCTION public.es_admin_hogar(p_id_hogar UUID)
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.hogar_miembros
        WHERE id_hogar = p_id_hogar
          AND auth_user_id = (SELECT auth.uid())
          AND rol = 'admin'
    );
$$;

CREATE OR REPLACE FUNCTION public.crear_hogar(p_nombre TEXT)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_id_hogar UUID;
    v_correo TEXT;
    v_nombre TEXT := trim(p_nombre);
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión para crear un hogar.';
    END IF;
    IF length(v_nombre) NOT BETWEEN 1 AND 60 THEN
        RAISE EXCEPTION 'El nombre debe tener entre 1 y 60 caracteres.';
    END IF;

    SELECT lower(email) INTO v_correo
    FROM auth.users
    WHERE id = auth.uid() AND email_confirmed_at IS NOT NULL;
    IF v_correo IS NULL THEN
        RAISE EXCEPTION 'Confirma tu correo antes de crear un hogar compartido.';
    END IF;
    IF EXISTS (SELECT 1 FROM public.hogar_miembros WHERE auth_user_id = auth.uid()) THEN
        RAISE EXCEPTION 'Tu cuenta ya pertenece a un hogar compartido.';
    END IF;

    INSERT INTO public.hogares (nombre, creado_por)
    VALUES (v_nombre, auth.uid())
    RETURNING id_hogar INTO v_id_hogar;

    INSERT INTO public.hogar_miembros (id_hogar, auth_user_id, correo, rol)
    VALUES (v_id_hogar, auth.uid(), v_correo, 'admin');

    RETURN v_id_hogar;
END;
$$;

CREATE OR REPLACE FUNCTION public.invitar_miembro_hogar(p_id_hogar UUID, p_correo TEXT)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_correo TEXT := lower(trim(p_correo));
    v_correo_actual TEXT;
    v_nombre_hogar TEXT;
    v_id_invitacion UUID;
BEGIN
    IF auth.uid() IS NULL OR NOT public.es_admin_hogar(p_id_hogar) THEN
        RAISE EXCEPTION 'Solo la persona administradora puede invitar miembros.';
    END IF;
    IF v_correo !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' THEN
        RAISE EXCEPTION 'Escribe un correo válido.';
    END IF;

    SELECT lower(email) INTO v_correo_actual
    FROM auth.users
    WHERE id = auth.uid() AND email_confirmed_at IS NOT NULL;
    IF v_correo_actual IS NULL THEN
        RAISE EXCEPTION 'Confirma tu correo antes de invitar miembros.';
    END IF;
    IF v_correo = v_correo_actual THEN
        RAISE EXCEPTION 'Ese correo ya administra este hogar.';
    END IF;
    IF EXISTS (
        SELECT 1 FROM public.hogar_miembros
        WHERE id_hogar = p_id_hogar AND lower(correo) = v_correo
    ) THEN
        RAISE EXCEPTION 'Esa persona ya pertenece al hogar.';
    END IF;

    SELECT nombre INTO v_nombre_hogar
    FROM public.hogares
    WHERE id_hogar = p_id_hogar;
    IF v_nombre_hogar IS NULL THEN
        RAISE EXCEPTION 'No se encontró el hogar.';
    END IF;

    UPDATE public.invitaciones_hogar
    SET invitado_por = auth.uid(),
        nombre_hogar = v_nombre_hogar,
        expira_en = CURRENT_TIMESTAMP + INTERVAL '7 days',
        fecha_creacion = CURRENT_TIMESTAMP
    WHERE id_hogar = p_id_hogar
      AND correo_invitado = v_correo
      AND estado = 'pendiente'
    RETURNING id_invitacion INTO v_id_invitacion;

    IF v_id_invitacion IS NULL THEN
        INSERT INTO public.invitaciones_hogar (
            id_hogar, nombre_hogar, correo_invitado, invitado_por
        )
        VALUES (p_id_hogar, v_nombre_hogar, v_correo, auth.uid())
        RETURNING id_invitacion INTO v_id_invitacion;
    END IF;

    RETURN v_id_invitacion;
END;
$$;

CREATE OR REPLACE FUNCTION public.aceptar_invitacion_hogar(p_id_invitacion UUID)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_invitacion public.invitaciones_hogar%ROWTYPE;
    v_correo TEXT;
BEGIN
    IF auth.uid() IS NULL THEN
        RAISE EXCEPTION 'Debes iniciar sesión para aceptar una invitación.';
    END IF;

    SELECT lower(email) INTO v_correo
    FROM auth.users
    WHERE id = auth.uid() AND email_confirmed_at IS NOT NULL;
    IF v_correo IS NULL THEN
        RAISE EXCEPTION 'Confirma tu correo antes de aceptar una invitación.';
    END IF;

    SELECT * INTO v_invitacion
    FROM public.invitaciones_hogar
    WHERE id_invitacion = p_id_invitacion
      AND estado = 'pendiente'
      AND expira_en > CURRENT_TIMESTAMP
      AND correo_invitado = v_correo
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'La invitación no existe, venció o pertenece a otro correo.';
    END IF;
    IF EXISTS (SELECT 1 FROM public.hogar_miembros WHERE auth_user_id = auth.uid()) THEN
        RAISE EXCEPTION 'Tu cuenta ya pertenece a un hogar compartido.';
    END IF;

    INSERT INTO public.hogar_miembros (id_hogar, auth_user_id, correo, rol)
    VALUES (v_invitacion.id_hogar, auth.uid(), v_correo, 'miembro');
    UPDATE public.invitaciones_hogar
    SET estado = 'aceptada'
    WHERE id_invitacion = p_id_invitacion;

    RETURN v_invitacion.id_hogar;
END;
$$;

CREATE OR REPLACE FUNCTION public.obtener_hogar_actual()
RETURNS TABLE (id_hogar UUID, nombre TEXT, rol TEXT, creado_por UUID)
LANGUAGE SQL
STABLE
SECURITY INVOKER
SET search_path = public, pg_temp
AS $$
    SELECT h.id_hogar, h.nombre, m.rol, h.creado_por
    FROM public.hogar_miembros m
    JOIN public.hogares h ON h.id_hogar = m.id_hogar
    WHERE m.auth_user_id = (SELECT auth.uid())
    LIMIT 1;
$$;

