-- Datos privados del hogar compartido. Estas tablas no reciben la política anónima general.
CREATE TABLE IF NOT EXISTS public.hogares (
    id_hogar UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nombre TEXT NOT NULL CHECK (length(trim(nombre)) BETWEEN 1 AND 60),
    creado_por UUID NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.hogar_miembros (
    id_hogar UUID NOT NULL REFERENCES public.hogares(id_hogar) ON DELETE CASCADE,
    auth_user_id UUID NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
    correo TEXT NOT NULL,
    rol TEXT NOT NULL CHECK (rol IN ('admin', 'miembro')),
    fecha_union TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id_hogar, auth_user_id)
);

CREATE TABLE IF NOT EXISTS public.invitaciones_hogar (
    id_invitacion UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    id_hogar UUID NOT NULL REFERENCES public.hogares(id_hogar) ON DELETE CASCADE,
    nombre_hogar TEXT NOT NULL,
    correo_invitado TEXT NOT NULL,
    invitado_por UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    estado TEXT NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente', 'aceptada', 'revocada')),
    expira_en TIMESTAMPTZ NOT NULL DEFAULT (CURRENT_TIMESTAMP + INTERVAL '7 days'),
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (correo_invitado = lower(correo_invitado))
);

CREATE UNIQUE INDEX IF NOT EXISTS invitaciones_hogar_pendientes_unicas
    ON public.invitaciones_hogar (id_hogar, correo_invitado)
    WHERE estado = 'pendiente';

CREATE INDEX IF NOT EXISTS invitaciones_hogar_correo_estado
    ON public.invitaciones_hogar (correo_invitado, estado, expira_en);

CREATE TABLE IF NOT EXISTS public.movimientos_hogar_compartidos (
    id_movimiento UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    id_hogar UUID NOT NULL REFERENCES public.hogares(id_hogar) ON DELETE CASCADE,
    creado_por UUID NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
    nombre_creador TEXT NOT NULL,
    tipo TEXT NOT NULL CHECK (tipo IN ('ingreso', 'gasto')),
    concepto TEXT NOT NULL CHECK (length(trim(concepto)) BETWEEN 1 AND 80),
    categoria TEXT NOT NULL CHECK (length(trim(categoria)) BETWEEN 1 AND 40),
    monto NUMERIC NOT NULL CHECK (monto > 0),
    fecha DATE NOT NULL DEFAULT CURRENT_DATE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS movimientos_hogar_compartidos_fecha
    ON public.movimientos_hogar_compartidos (id_hogar, fecha DESC);

